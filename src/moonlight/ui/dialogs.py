"""Action preview, consent, and provider warning dialogs for Moonlight UI.

Enforces:
- Every action preview displays exact path, size, mtime, destination, and changes.
- Confirmation token is generated by preview_action and held strictly in memory.
- Confirmation token is never read from report text or model output.
- Extra confirmation checkbox is required for review_first paths.
- Execution happens only from the dialog's Confirm button through the policy layer.
- UI code never calls OS functions directly.
"""

from __future__ import annotations

from collections.abc import Callable
from typing import Any

from PySide6.QtCore import Signal
from PySide6.QtWidgets import (
    QCheckBox,
    QDialog,
    QFrame,
    QHBoxLayout,
    QLabel,
    QPushButton,
    QScrollArea,
    QVBoxLayout,
    QWidget,
)

from moonlight.policy.actions import (
    ActionPreview,
    ActionType,
    ExecutionResult,
    ProposedAction,
)
from moonlight.policy.engine import (
    execute_action,
    preview_action,
)
from moonlight.ui.theme import COLORS, RADII, SPACING


def _format_size(num_bytes: int | None) -> str:
    """Format byte size into human readable string with exact byte count."""
    if num_bytes is None:
        return "N/A"
    if num_bytes < 1024:
        return f"{num_bytes} bytes"
    elif num_bytes < 1024 * 1024:
        kb = num_bytes / 1024.0
        return f"{kb:.1f} KB ({num_bytes:,} bytes)"
    elif num_bytes < 1024 * 1024 * 1024:
        mb = num_bytes / (1024.0 * 1024.0)
        return f"{mb:.2f} MB ({num_bytes:,} bytes)"
    else:
        gb = num_bytes / (1024.0 * 1024.0 * 1024.0)
        return f"{gb:.2f} GB ({num_bytes:,} bytes)"


class ActionPreviewDialog(QDialog):
    """Consent and dry-run preview dialog for policy-controlled actions.

    The confirmation token returned by preview_action is held strictly in memory
    inside this dialog and never read from model or report text.
    """

    action_executed = Signal(object)  # ExecutionResult

    def __init__(
        self,
        action: ProposedAction,
        preview: ActionPreview | None = None,
        hooks: dict[str, Callable[..., Any]] | None = None,
        parent: QWidget | None = None,
    ) -> None:
        super().__init__(parent)
        self.setObjectName("action_preview_dialog")
        self.setWindowTitle("Action Consent & Dry-Run Preview - Moonlight Policy")
        self.setMinimumWidth(600)
        self.setMinimumHeight(440)
        self.setModal(True)

        self._action = action
        self._hooks = hooks or {}

        # 1. Preview from policy layer (held in memory)
        self._preview = preview if preview is not None else preview_action(action)
        self._confirmation_token: str | None = self._preview.confirmation_token
        self._result: ExecutionResult | None = None

        self._init_ui()

    @property
    def preview(self) -> ActionPreview:
        return self._preview

    @property
    def execution_result(self) -> ExecutionResult | None:
        return self._result

    @property
    def confirmation_token(self) -> str | None:
        return self._confirmation_token

    def set_confirmation_token_for_test(self, token: str | None) -> None:
        """Testing helper to simulate tampered or missing tokens."""
        self._confirmation_token = token

    def _init_ui(self) -> None:
        c = COLORS
        r = RADII

        main_layout = QVBoxLayout(self)
        main_layout.setContentsMargins(SPACING.md, SPACING.md, SPACING.md, SPACING.md)
        main_layout.setSpacing(SPACING.md)

        # Header card
        header_card = QFrame()
        header_card.setObjectName("card")
        header_layout = QVBoxLayout(header_card)
        header_layout.setContentsMargins(SPACING.sm, SPACING.sm, SPACING.sm, SPACING.sm)

        title_label = QLabel("Action Consent & Dry-Run Preview")
        title_label.setObjectName("header_title")
        header_layout.addWidget(title_label)

        sub_label = QLabel(
            "Every action in Moonlight must be dry-run previewed and confirmed "
            "before execution through the policy layer."
        )
        sub_label.setWordWrap(True)
        sub_label.setStyleSheet(f"color: {c.text_secondary};")
        header_layout.addWidget(sub_label)

        main_layout.addWidget(header_card)

        # Details scroll area
        scroll = QScrollArea()
        scroll.setWidgetResizable(True)
        scroll.setFrameShape(QFrame.Shape.NoFrame)

        content = QWidget()
        content_layout = QVBoxLayout(content)
        content_layout.setSpacing(SPACING.sm)

        # Action overview card
        overview_card = QFrame()
        overview_card.setObjectName("card")
        ov_layout = QVBoxLayout(overview_card)

        # Action type row
        act_row = QHBoxLayout()
        act_name_label = QLabel("Proposed Action:")
        act_name_label.setStyleSheet(f"color: {c.text_muted}; font-weight: 600;")
        act_val_label = QLabel(self._action.action_type.replace("_", " ").upper())
        act_val_label.setStyleSheet(
            f"color: {c.accent_primary}; font-weight: 700; font-size: 14px;"
        )
        act_row.addWidget(act_name_label)
        act_row.addWidget(act_val_label)
        act_row.addStretch()

        # Policy status chip
        status_chip = QLabel()
        if self._preview.allowed:
            status_chip.setText("POLICY ALLOWED")
            status_chip.setStyleSheet(
                f"background-color: {c.risk_low_bg}; color: {c.risk_low_text}; "
                f"border: 1px solid {c.risk_low_border}; font-weight: 700; "
                f"font-size: 11px; padding: 2px 8px; border-radius: {r.pill}px;"
            )
        else:
            status_chip.setText("BLOCKED BY POLICY")
            status_chip.setStyleSheet(
                f"background-color: {c.risk_high_bg}; color: {c.risk_high_text}; "
                f"border: 1px solid {c.risk_high_border}; font-weight: 700; "
                f"font-size: 11px; padding: 2px 8px; border-radius: {r.pill}px;"
            )
        act_row.addWidget(status_chip)
        ov_layout.addLayout(act_row)

        # Target Path / Subject
        target_display = (
            self._preview.resolved_target_path
            or self._action.target_path
            or self._action.target_process
            or self._action.target_id
            or self._action.hash_value
            or "Unknown Target"
        )
        target_row = QVBoxLayout()
        target_title = QLabel("Target Location / Subject:")
        target_title.setStyleSheet(f"color: {c.text_muted}; font-weight: 600;")
        target_val = QLabel(str(target_display))
        target_val.setWordWrap(True)
        target_val.setStyleSheet(
            f"color: {c.text_primary}; font-weight: 600; "
            f"background-color: {c.bg_canvas}; padding: 6px 10px; "
            f"border-radius: {r.sm}px; border: 1px solid {c.border_subtle};"
        )
        target_row.addWidget(target_title)
        target_row.addWidget(target_val)
        ov_layout.addLayout(target_row)

        content_layout.addWidget(overview_card)

        # Rejection card if blocked
        if not self._preview.allowed:
            blocked_card = QFrame()
            blocked_card.setStyleSheet(
                f"background-color: {c.risk_high_bg}; border: 1px solid "
                f"{c.risk_high_border}; border-radius: {r.md}px; padding: 12px;"
            )
            blocked_layout = QVBoxLayout(blocked_card)
            b_title = QLabel("Execution Prohibited by Policy Guardrails")
            b_title.setStyleSheet(
                f"color: {c.risk_high_text}; font-weight: 700; font-size: 13px;"
            )
            b_desc = QLabel(
                self._preview.rejection_reason or "Policy rejected this action."
            )
            b_desc.setWordWrap(True)
            b_desc.setStyleSheet(f"color: {c.text_primary};")
            blocked_layout.addWidget(b_title)
            blocked_layout.addWidget(b_desc)
            content_layout.addWidget(blocked_card)

        # Details card for file/recycle operations
        if self._preview.allowed:
            details_card = QFrame()
            details_card.setObjectName("card")
            det_layout = QVBoxLayout(details_card)

            d_title = QLabel("Target Details & Impact")
            d_title.setStyleSheet(f"color: {c.text_secondary}; font-weight: 600;")
            det_layout.addWidget(d_title)

            # Metadata grid
            grid_layout = QVBoxLayout()

            size_str = _format_size(self._preview.target_size_bytes)
            size_lbl = QLabel(f"• Target Size: {size_str}")
            size_lbl.setStyleSheet(f"color: {c.text_secondary};")
            grid_layout.addWidget(size_lbl)

            if self._preview.target_item_count is not None:
                item_lbl = QLabel(
                    f"• Items Affected: {self._preview.target_item_count}"
                )
                item_lbl.setStyleSheet(f"color: {c.text_secondary};")
                grid_layout.addWidget(item_lbl)

            if self._preview.target_mtime is not None:
                mtime_str = self._preview.target_mtime.strftime("%Y-%m-%d %H:%M:%S UTC")
                mtime_lbl = QLabel(f"• Last Modified: {mtime_str}")
                mtime_lbl.setStyleSheet(f"color: {c.text_secondary};")
                grid_layout.addWidget(mtime_lbl)

            dest_str = self._preview.destination or (
                "Windows Explorer"
                if self._action.action_type == ActionType.OPEN_FILE_LOCATION
                else "System Clipboard"
            )
            dest_lbl = QLabel(f"• Destination: {dest_str}")
            dest_lbl.setStyleSheet(f"color: {c.text_secondary}; font-weight: 600;")
            grid_layout.addWidget(dest_lbl)

            if self._preview.storage_category:
                cat_lbl = QLabel(
                    f"• Storage Classification: {self._preview.storage_category}"
                )
                cat_lbl.setStyleSheet(f"color: {c.text_secondary};")
                grid_layout.addWidget(cat_lbl)

            det_layout.addLayout(grid_layout)

            # Changes list
            if self._preview.changes:
                ch_title = QLabel("Planned Changes:")
                ch_title.setStyleSheet(
                    f"color: {c.text_muted}; font-weight: 600; margin-top: 8px;"
                )
                det_layout.addWidget(ch_title)
                for ch in self._preview.changes:
                    ch_item = QLabel(f"  → {ch}")
                    ch_item.setWordWrap(True)
                    ch_item.setStyleSheet(f"color: {c.text_primary};")
                    det_layout.addWidget(ch_item)

            content_layout.addWidget(details_card)

        # Extra confirmation checkbox for review-first paths
        self.extra_checkbox: QCheckBox | None = None
        if self._preview.requires_extra_confirmation and self._preview.allowed:
            extra_card = QFrame()
            extra_card.setStyleSheet(
                f"background-color: {c.warning_bg}; border: 1px solid "
                f"{c.warning_border}; border-radius: {r.md}px; padding: 10px;"
            )
            extra_layout = QVBoxLayout(extra_card)
            warn_lbl = QLabel(
                "ATTENTION: Path is classified as 'review_first'. "
                "Explicit extra confirmation is required to proceed."
            )
            warn_lbl.setWordWrap(True)
            warn_lbl.setStyleSheet(
                f"color: {c.warning_text}; font-weight: 700; font-size: 12px;"
            )
            extra_layout.addWidget(warn_lbl)

            self.extra_checkbox = QCheckBox(
                "I have verified this path and confirm sending it to the Recycle Bin."
            )
            self.extra_checkbox.setObjectName("extra_confirm_checkbox")
            self.extra_checkbox.setStyleSheet(
                f"color: {c.text_primary}; font-weight: 600;"
            )
            self.extra_checkbox.stateChanged.connect(self._on_extra_toggled)
            extra_layout.addWidget(self.extra_checkbox)

            content_layout.addWidget(extra_card)

        # Execution error display banner (hidden initially)
        self.error_banner = QLabel()
        self.error_banner.setObjectName("dialog_error_banner")
        self.error_banner.setWordWrap(True)
        self.error_banner.setVisible(False)
        self.error_banner.setStyleSheet(
            f"background-color: {c.risk_high_bg}; color: {c.risk_high_text}; "
            f"border: 1px solid {c.risk_high_border}; padding: 8px; "
            f"border-radius: {r.md}px; font-weight: 600;"
        )
        content_layout.addWidget(self.error_banner)

        content_layout.addStretch()
        scroll.setWidget(content)
        main_layout.addWidget(scroll)

        # Bottom button bar
        button_row = QHBoxLayout()
        button_row.setSpacing(SPACING.sm)

        self.cancel_button = QPushButton("Cancel")
        self.cancel_button.setObjectName("cancel_button")
        self.cancel_button.clicked.connect(self.reject)
        button_row.addWidget(self.cancel_button)

        button_row.addStretch()

        self.confirm_button = QPushButton("Confirm & Execute")
        self.confirm_button.setObjectName("confirm_button")
        self.confirm_button.setProperty("primary", "true")
        self.confirm_button.clicked.connect(self._on_confirm_clicked)

        # Determine initial enabled state
        if not self._preview.allowed:
            self.confirm_button.setEnabled(False)
        elif self._preview.requires_extra_confirmation:
            self.confirm_button.setEnabled(False)
        else:
            self.confirm_button.setEnabled(True)

        button_row.addWidget(self.confirm_button)
        main_layout.addLayout(button_row)

    def _on_extra_toggled(self, state: int) -> None:
        """Enable or disable Confirm button based on extra confirmation."""
        if self._preview.allowed and self.extra_checkbox:
            self.confirm_button.setEnabled(self.extra_checkbox.isChecked())

    def _on_confirm_clicked(self) -> None:
        """Execute confirmed action through policy layer with in-memory token."""
        if not self._preview.allowed:
            return

        extra_confirmed = (
            self.extra_checkbox.isChecked() if self.extra_checkbox else False
        )

        # Execute through policy layer
        result = execute_action(
            action=self._action,
            preview=self._preview,
            confirmed=True,
            confirmation_token=self._confirmation_token,
            extra_confirmed=extra_confirmed,
            hooks=self._hooks,
        )

        self._result = result
        self.action_executed.emit(result)

        if result.success:
            self.accept()
        else:
            # Display failure reason in dialog
            err_msg = result.error or result.message
            self.error_banner.setText(f"Execution Failed: {err_msg}")
            self.error_banner.setVisible(True)


class LiveProviderWarningDialog(QDialog):
    """Warning confirmation dialog when selecting a cloud provider in Live mode."""

    def __init__(
        self,
        provider_name: str,
        parent: QWidget | None = None,
    ) -> None:
        super().__init__(parent)
        self.setObjectName("live_provider_warning_dialog")
        self.setWindowTitle("Live Mode Data Transmission Warning - Moonlight")
        self.setMinimumWidth(500)
        self.setModal(True)

        c = COLORS
        r = RADII

        layout = QVBoxLayout(self)
        layout.setContentsMargins(SPACING.md, SPACING.md, SPACING.md, SPACING.md)
        layout.setSpacing(SPACING.md)

        # Warning banner card
        warn_card = QFrame()
        warn_card.setStyleSheet(
            f"background-color: {c.warning_bg}; border: 1px solid "
            f"{c.warning_border}; border-radius: {r.lg}px; padding: 16px;"
        )
        w_layout = QVBoxLayout(warn_card)

        w_title = QLabel("⚠️ External Model Provider Warning in Live Mode")
        w_title.setStyleSheet(
            f"color: {c.warning_text}; font-weight: 700; font-size: 15px;"
        )
        w_layout.addWidget(w_title)

        w_text = QLabel(
            f"You are selecting external provider '{provider_name}' in Live mode.\n\n"
            "In Live mode, evidence is collected from this real machine. "
            "Although the minimizer redacts private identifiers, paths, and IPs, "
            "the minimized evidence payload WILL BE TRANSMITTED across the network "
            f"to the '{provider_name}' API endpoint.\n\n"
            "To keep all evidence strictly local, use the 'mock' provider."
        )
        w_text.setWordWrap(True)
        w_text.setStyleSheet(f"color: {c.text_primary}; line-height: 1.4;")
        w_layout.addWidget(w_text)

        layout.addWidget(warn_card)

        # Checkbox confirmation
        self.ack_checkbox = QCheckBox(
            "I understand that minimized live-machine evidence will leave this machine."
        )
        self.ack_checkbox.setStyleSheet(
            f"color: {c.text_primary}; font-weight: 600; margin-top: 4px;"
        )
        self.ack_checkbox.stateChanged.connect(self._on_ack_changed)
        layout.addWidget(self.ack_checkbox)

        # Buttons
        button_row = QHBoxLayout()
        button_row.setSpacing(SPACING.sm)

        self.cancel_button = QPushButton("Keep Local Mock")
        self.cancel_button.setObjectName("cancel_warning_button")
        self.cancel_button.clicked.connect(self.reject)
        button_row.addWidget(self.cancel_button)

        button_row.addStretch()

        self.proceed_button = QPushButton("Proceed with Cloud Provider")
        self.proceed_button.setObjectName("proceed_warning_button")
        self.proceed_button.setProperty("danger", "true")
        self.proceed_button.setEnabled(False)
        self.proceed_button.clicked.connect(self.accept)
        button_row.addWidget(self.proceed_button)

        layout.addLayout(button_row)

    def _on_ack_changed(self, state: int) -> None:
        self.proceed_button.setEnabled(self.ack_checkbox.isChecked())
